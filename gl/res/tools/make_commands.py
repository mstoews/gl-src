#!/usr/bin/env python3
"""Write gl/port/CommandsTable.inc, the command table's rows, from the MANILA
menu in gl/res/gl.rc (spec #8 8, plan S8-M0 task 4).

The workspace builds the menu bar, the navigation pane and the rights from
these rows, so the table starts as exactly the menu prune_rc.py makes. Run it
after prune_rc.py whenever the menu changes; /checkres compares the menu built
from the table with MANILA loaded from the resources, item by item.

usage: python -I gl/res/tools/make_commands.py <repo-root>
"""
import os
import re
import sys

ROOT = sys.argv[1] if len(sys.argv) > 1 else '.'
RC = os.path.join(ROOT, 'gl', 'res', 'gl.rc')
OUT = os.path.join(ROOT, 'gl', 'port', 'CommandsTable.inc')

FLAGS = {'GRAYED': 'kGrayed', 'INACTIVE': 'kGrayed', 'CHECKED': 'kChecked', 'MENUBARBREAK': 'kBarBreak',
         'MENUBREAK': 'kBreak', 'HELP': 'kHelp'}


def read_rc(path):
    data = open(path, 'rb').read()
    if data[:2] in (b'\xff\xfe', b'\xfe\xff'):
        return data.decode('utf-16')
    return data.decode('cp1252')


def rc_string(s):
    """An rc string literal's body -> a C++ wide literal's body."""
    s = s.replace('""', '"')          # rc doubles a quote; C++ escapes it
    out = []
    for ch in s:
        if ch == '"':
            out.append('\\"')
        elif ord(ch) > 126:
            out.append('\\x%04X' % ord(ch))
        else:
            out.append(ch)
    return ''.join(out)


def main():
    text = read_rc(RC)
    start = text.find('\nMANILA MENU')
    if start < 0:
        sys.exit('MANILA MENU not found in ' + RC)
    rows = []
    depth = -1
    item = re.compile(r'MENUITEM\s+"((?:[^"]|"")*)"\s*,\s*([A-Za-z_0-9]+)\s*(?:,\s*(.*))?$')
    popup = re.compile(r'POPUP\s+"((?:[^"]|"")*)"')
    for raw in text[start + 1:].splitlines()[1:]:   # the lines after "MANILA MENU"
        line = raw.strip()
        if not line or line.startswith('//'):
            continue
        if line == '{':
            depth += 1
            continue
        if line == '}':
            depth -= 1
            if depth < 0:
                break
            continue
        if line.startswith('MENUITEM SEPARATOR'):
            rows.append('    {%d, Kind::Separator, L"", 0, 0},' % depth)
            continue
        m = popup.match(line)
        if m:
            rows.append('    {%d, Kind::Popup, L"%s", 0, 0},' % (depth, rc_string(m.group(1))))
            continue
        m = item.match(line)
        if m:
            flags = [FLAGS[f.strip()] for f in (m.group(3) or '').split(',') if f.strip() in FLAGS]
            rows.append('    {%d, Kind::Item, L"%s", %s, %s},' % (depth, rc_string(m.group(1)), m.group(2),
                                                                  ' | '.join(flags) if flags else '0'))
            continue
        sys.exit('make_commands.py: a MANILA line it can\'t read: ' + line)
    header = ('// CommandsTable.inc - generated by gl/res/tools/make_commands.py from the\n'
              '// MANILA menu in gl/res/gl.rc. Do not edit: change prune_rc.py, then run both.\n'
              '// One row per menu line, in order: {depth, kind, text, command ID, flags}.\n')
    with open(OUT, 'w', newline='\r\n') as f:
        f.write(header)
        f.write('\n'.join(rows) + '\n')
    items = sum(1 for r in rows if 'Kind::Item' in r)
    print('%s: %d rows, %d commands' % (OUT, len(rows), items))


main()
